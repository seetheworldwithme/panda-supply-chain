"""Generate auth and contract Excel metadata from the read-only Java source.

PANDA_JAVA_ROOT points to saas-hyqc. Does not access credentials or the database.
"""
import ast
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JAVA = Path(os.environ.get("PANDA_JAVA_ROOT", "/Volumes/coding/HBuilderxProject/panda/saas-hyqc"))
# Reuse only pure parser definitions; importing the old generator would overwrite metadata.
tree = ast.parse((ROOT / "tools/gen-commonrest.py").read_text())
scope = {"re": re, "os": os}
nodes = [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name in ("read", "parse_entity", "camel_to_underline")]
scope["KIND"] = {"String": "s", "Integer": "i", "Long": "l", "BigDecimal": "d", "Boolean": "b", "boolean": "b", "LocalDate": "D", "LocalDateTime": "t"}
exec(compile(ast.Module(body=nodes, type_ignores=[]), "java-entity-parser", "exec"), scope)
parse, snake = scope["parse_entity"], scope["camel_to_underline"]
roots = [JAVA / x / y / "src/main/java" for x, y in (
    ("saas-supply-chain", "saas-auth"), ("saas-hyqc", "hyqc-auth"),
    ("saas-hyqc", "hyqc-core"), ("saas-supply-chain", "saas-contract"),
    ("saas-supply-chain", "saas-core"), ("saas-supply-chain", "saas-capital"),
    ("saas-supply-chain", "saas-logistics"), ("saas-supply-chain", "saas-bill"))]


def locate(name):
    return next(p for root in roots for p in sorted(root.rglob(name + ".java")))


def j(value):
    return json.dumps(value, ensure_ascii=False)


def arr(values):
    return "[]string{" + ",".join(map(j, values)) + "}"


names = ["ChainAuthAuthenLog", "ChainAuthAuthority", "ChainAuthAuthorityRole", "ChainAuthAuthorityUser",
         "ChainAuthMenuRole", "ChainAuthMenuUser", "ChainAuthSecret", "ChainAuthUseRole", "ChainAuthMenu", "ChainAuthUser",
         "ChainContractExtend", "ChainContractSupplier", "ChainContract", "ChainCapitalSettlement", "ChainCapitalDetailed",
         "ChainBill", "ChainBillRate", "ChainLogistics", "ChainLogisticsWeighingList", "ChainBasicEnterprise", "ChainAuthChatAuthorization"]
out = ["// Code generated by backend/tools/gen-authrest.py. DO NOT EDIT.", "package commonrest", "var authRestEnts = map[string]*ent{"]
for name in names:
    path = (JAVA / "saas-hyqc/hyqc-auth/src/main/java/com/saas/auth/model/ChainBasicEnterprise.java") if name == "ChainBasicEnterprise" else locate(name)
    _, fields = parse(str(path))
    non = [x for x in fields if not x["carrier"]]
    mapper_paths = [p for root in roots for p in sorted(root.rglob(name + "Mapper.java"))]
    mapper = mapper_paths[0].read_text() if mapper_paths else ""
    sqls = {m[2]: m[1] for m in re.finditer(r'@Select\("((?:[^"\\]|\\.)*)"\)\s*(?:@\w+(?:\([^)]*\))?\s*)*[\w<>.,\s\[\]?]+?\s+(\w+)\(', mapper)}
    parts = ["table:" + j(snake(name)), "fill:" + str(any(x["fill"] for x in non)).lower(),
             "echo:" + str(name not in ("ChainAuthAuthenLog", "ChainAuthMenuUser", "ChainAuthSecret")).lower(),
             "keys:" + arr([x["name"] for x in fields]), "dbcols:" + arr([snake(x["name"]) for x in non]),
             "types:[]jf{" + ",".join("{" + j(x["name"]) + "," + j(x["kind"]) + "}" for x in fields) + "}",
             "q:[]sqlf{" + ",".join("{" + j(x["name"]) + "," + j(x["kind"] if x["kind"] in ("i", "D") else "w") + "}" for x in non if x["excel"]) + "}"]
    for kind, key in (("BigDecimal", "decimals"), ("LocalDate", "dates"), ("Boolean", "bools")):
        parts.append(key + ":" + arr([x["name"] for x in non if x["type"] == kind]))
    parts.append("isoTimes:" + arr([x["name"] for x in non if x["kind"] == "T"]))
    parts.append("excel:[]impField{" + ",".join("{" + ",".join([j(x["excel"][1]), j(snake(x["name"])), j(scope["KIND"].get(x["type"], x["kind"])), str(x["sys"]).lower(), str(x["dict"]).lower(), str(x["notbank"]).lower(), str(x["datecheck"]).lower(), str(x["numbercheck"]).lower()]) + "}" for x in fields if x["excel"]) + "}")
    for method, key in (("listByPage", "listSQL"), ("listNoPage", "listNoSQL")):
        parts.append(key + ":" + j(sqls.get(method, "")))
    out.append(j(name) + ": {" + ",\n".join(parts) + "},")
out.append("}")
(ROOT / "internal/commonrest/auth_meta_gen.go").write_text("\n".join(out) + "\n")
